#!/usr/bin/env python3
"""Generate the native GL helper's encoders and decoders (shim/docs/gl-helper.md).

    python3 shim/tools/gen_glproxy.py          # rewrites shim/src/glproto_ops.h, glproxy_gen.h, glhelper_gen.h

Input: shim/src/glproxy.list (the proxied functions; prototypes from the SDK's OpenGL/gl3.h unless given inline) and
peload.c's D3DGLApi struct (which functions are members of the G table). The outputs are committed, so building
needs only clang. Functions marked `custom` get only declarations here; glproxy.c / glhelper.c implement them.
"""
import os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'src')

def sdk_gl3():
    sdk = subprocess.check_output(['xcrun', '--show-sdk-path'], text=True).strip()
    return open(os.path.join(sdk, 'System/Library/Frameworks/OpenGL.framework/Headers/gl3.h')).read()

def parse_args(s):
    s = s.strip()
    if s in ('', 'void'): return []
    out = []
    for i, a in enumerate(s.split(',')):
        a = a.strip()
        m = re.match(r'^(.*?)([A-Za-z_][A-Za-z0-9_]*)$', a)
        ty, nm = (m.group(1).strip(), m.group(2)) if m else (a, 'a%d' % i)
        if not ty: ty, nm = nm, 'a%d' % i
        out.append((ty.replace('GLvoid', 'void'), nm))
    return out

ONE = {'GLenum', 'GLuint', 'GLint', 'GLsizei', 'GLbitfield', 'GLboolean', 'GLubyte', 'GLshort', 'GLushort', 'GLbyte', 'GLchar'}
FLT = {'GLfloat', 'GLclampf'}
TWO = {'GLdouble', 'GLclampd', 'GLintptr', 'GLsizeiptr', 'GLint64', 'GLuint64'}
# object-name parameters (by GL's own parameter names) -> namespace
NAMES = {'texture': 'TEX', 'buffer': 'BUF', 'framebuffer': 'FBO', 'renderbuffer': 'RBO', 'program': 'OBJ',
         'shader': 'OBJ', 'sampler': 'SMP', 'pipeline': 'PIPE'}
OFFSET_PTRS = {'indices', 'pointer'}   # core profile: offsets into the bound buffer, never client memory

def ns_of(fn, ty, nm):
    if ty != 'GLuint': return None
    if nm in NAMES: return NAMES[nm]
    if nm == 'array' and fn == 'BindVertexArray': return 'VAO'
    if nm == 'id' and 'Query' in fn: return 'QRY'
    return None

def words(ty, nm):
    if ty in ONE: return 1
    if ty in FLT: return 1
    if ty in TWO: return 2
    if '*' in ty and nm in OFFSET_PTRS: return 2
    raise ValueError('unsupported argument %s %s' % (ty, nm))

def main():
    gl3 = sdk_gl3()
    protos = {}
    for m in re.finditer(r'^GLAPI ([^\n;]*?) APIENTRY gl(\w+) \(([^)\n]*)\)[^;\n]*;', gl3, re.M):
        protos[m.group(2)] = (m.group(1).strip(), m.group(3))
    peload = open(os.path.join(SRC, 'peload.c')).read()
    gs = peload[peload.index('typedef struct {\n    unsigned(*CreateShader)'):]
    gs = gs[:gs.index('} D3DGLApi;')]
    gmembers = set(re.findall(r'\(\*\s*([A-Za-z0-9_]+)\s*\)\s*\(', gs))

    fns = []   # (name, ret, args, custom)
    for line in open(os.path.join(SRC, 'glproxy.list')):
        line = line.split('#', 1)[0].strip()
        if not line: continue
        custom = line.endswith(' custom')
        if custom: line = line[:-len(' custom')].strip()
        if ' = ' in line:
            name, proto = line.split(' = ', 1)
            m = re.match(r'^(.*?)\s*(\w+)\((.*)\)$', proto.strip())
            ret, args = m.group(1).strip(), m.group(3)
        else:
            name = line
            if name not in protos: sys.exit('gl%s: not in gl3.h; give its prototype in glproxy.list' % name)
            ret, args = protos[name]
        ret = ret.replace('GLvoid', 'void').replace('const GLubyte *', 'const GLubyte*')
        fns.append((name.strip(), ret, parse_args(args), custom))

    hdr = '// GENERATED by shim/tools/gen_glproxy.py from shim/src/glproxy.list -- do not edit.\n'
    # ---- opcodes ----
    ops = [hdr, '#pragma once\nenum {\n    GLOP_FIRST_GL = 64,   // below: protocol opcodes (glproto.h)\n']
    for i, (n, *_ ) in enumerate(fns):
        ops.append('    GLOP_%s = %d,\n' % (n, 64 + i))
    ops.append('    GLOP_COUNT = %d };\n' % (64 + len(fns)))
    ops.append('static const char* const glop_names[%d] = {\n' % len(fns))
    ops.append(''.join('    "gl%s",\n' % f[0] for f in fns) + '};\n')
    open(os.path.join(SRC, 'glproto_ops.h'), 'w').write(''.join(ops))

    # ---- loader side ----
    c = [hdr, '// Included by glproxy.c. glr_X = the real function, glp_X = the dispatcher (encode when t_glp).\n']
    for n, ret, args, custom in fns:
        sig = ', '.join('%s %s' % a for a in args) or 'void'
        c.append('static %s (*glr_%s)(%s);\n' % (ret, n, sig))
    for n, ret, args, custom in fns:
        sig = ', '.join('%s %s' % a for a in args) or 'void'
        call = ', '.join(a[1] for a in args)
        if custom:
            c.append('static %s glp_%s(%s);\n' % (ret, n, sig)); continue
        assert ret == 'void', n
        nw = sum(words(t, a) for t, a in args)
        body = ['static void glp_%s(%s){ if(!t_glp){ glr_%s(%s); return; }' % (n, sig, n, call)]
        body.append(' uint32_t*w=glp_cmd(GLOP_%s,%d);' % (n, nw) if nw else ' (void)glp_cmd(GLOP_%s,0);' % n)
        k = 0
        for t, a in args:
            if t in ONE: body.append(' w[%d]=(uint32_t)%s;' % (k, a)); k += 1
            elif t in FLT: body.append(' memcpy(&w[%d],&%s,4);' % (k, a)); k += 1
            elif t in TWO and t in ('GLdouble', 'GLclampd'): body.append(' memcpy(&w[%d],&%s,8);' % (k, a)); k += 2
            elif t in TWO: body.append(' { uint64_t v=(uint64_t)%s; memcpy(&w[%d],&v,8); }' % (a, k)); k += 2
            else: body.append(' { uint64_t v=(uint64_t)(uintptr_t)%s; memcpy(&w[%d],&v,8); }' % (a, k)); k += 2
        body.append(' glp_end(); }\n')
        c.append(''.join(body))
    c.append('typedef struct { const char* name; void** real; void* disp; } GlpFn;\n')
    c.append('static GlpFn g_glp_fns[] = {\n' + ''.join('    {"gl%s",(void**)&glr_%s,(void*)glp_%s},\n' % (n, n, n) for n, *_ in fns) + '};\n')
    c.append('// G table members: real = the loaded pointer, G.X = the dispatcher\n')
    c.append('static void glp_install_G(void){\n')
    for n, *_ in fns:
        if n in gmembers: c.append('    if(G.%s){ glr_%s=(void*)G.%s; G.%s=(void*)glp_%s; }\n' % (n, n, n, n, n))
    c.append('}\n')
    open(os.path.join(SRC, 'glproxy_gen.h'), 'w').write(''.join(c))

    # ---- helper side ----
    h = [hdr, '// Included by glhelper.c inside its decode switch: case GLOP_X: ... break;\n']
    decl = [hdr, '// Included by glhelper.c: the hand-written decoders.\n']
    for n, ret, args, custom in fns:
        if custom:
            decl.append('static void hx_%s(const uint32_t*p,uint32_t n);\n' % n)
            h.append('case GLOP_%s: hx_%s(p,n); break;\n' % (n, n)); continue
        k = 0; parts = []
        for t, a in args:
            ns = ns_of(n, t, a)
            if ns: parts.append('glh_name(NS_%s,p[%d])' % (ns, k)); k += 1
            elif t in ONE:
                cast = 'GLint' if t == 'GLint' else ('GLsizei' if t == 'GLsizei' else t)
                parts.append('(%s)p[%d]' % (cast, k)); k += 1
            elif t in FLT: parts.append('glh_f32(p+%d)' % k); k += 1
            elif t in ('GLdouble', 'GLclampd'): parts.append('glh_f64(p+%d)' % k); k += 2
            elif t in TWO: parts.append('(%s)glh_u64(p+%d)' % (t, k)); k += 2
            else: parts.append('(%s)(uintptr_t)glh_u64(p+%d)' % (t, k)); k += 2
        h.append('case GLOP_%s: if(glh_fn.%s) glh_fn.%s(%s); break;\n' % (n, n, n, ', '.join(parts)))
    open(os.path.join(SRC, 'glhelper_gen.h'), 'w').write(''.join(h))
    # helper function table (dlsym'd natively: TexStorage2D & co. may be absent)
    t = [hdr, '// Included by glhelper.c: the helper\'s GL function table.\n', 'static struct {\n']
    for n, ret, args, custom in fns:
        t.append('    %s (*%s)(%s);\n' % (ret, n, ', '.join(a[0] for a in args) or 'void'))
    t.append('} glh_fn;\n')
    t.append('static void glh_load(void){\n' + ''.join('    glh_fn.%s=dlsym(RTLD_DEFAULT,"gl%s");\n' % (n, n) for n, *_ in fns) + '}\n')
    open(os.path.join(SRC, 'glhelper_fns.h'), 'w').write(''.join(t) + ''.join(decl))
    print('%d functions (%d generated, %d custom); %d G members' % (len(fns), sum(1 for f in fns if not f[3]), sum(1 for f in fns if f[3]), len(gmembers & {f[0] for f in fns})))

main()
